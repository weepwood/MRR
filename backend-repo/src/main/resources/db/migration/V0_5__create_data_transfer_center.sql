    date_raw                TEXT,
    type_raw                TEXT,
    pages_raw               TEXT,
    sjh_raw                 TEXT,
    patientname_raw         TEXT,
    inpatientdepartment_raw TEXT,
    patientid_raw           TEXT,
    dischargedate_raw       TEXT,
    bah                     TEXT,
    sjh                     TEXT,
    archive_date            DATE,
    discharge_date          DATE,
    pages                   INTEGER,
    source_row_hash         VARCHAR(32),
    is_valid                BOOLEAN,
