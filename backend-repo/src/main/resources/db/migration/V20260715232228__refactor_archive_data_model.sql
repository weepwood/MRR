CREATE OR REPLACE FUNCTION app.normalize_medical_record_code(p_value TEXT)
RETURNS TEXT
LANGUAGE SQL
IMMUTABLE
PARALLEL SAFE
AS $$
SELECT CASE
    WHEN NULLIF(BTRIM(p_value), '') IS NULL THEN NULL
    WHEN BTRIM(p_value) ~ '^[0-9]{1,8}$' THEN LPAD(BTRIM(p_value), 8, '0')
    ELSE BTRIM(p_value)
END
$$;

COMMENT ON FUNCTION app.normalize_medical_record_code(TEXT)
    IS '规范化病案号/上架号：空白转 NULL，1~8 位纯数字补齐为 8 位';

CREATE OR REPLACE FUNCTION app.try_parse_date(p_value TEXT)
RETURNS DATE
LANGUAGE plpgsql
IMMUTABLE
PARALLEL SAFE
AS $$
DECLARE
    parts TEXT[];
BEGIN
    IF NULLIF(BTRIM(p_value), '') IS NULL THEN
        RETURN NULL;
    END IF;

    parts := regexp_match(BTRIM(p_value), '^(\d{4})[-/](\d{1,2})[-/](\d{1,2})$');
    IF parts IS NULL THEN
        RETURN NULL;
    END IF;

    RETURN make_date(parts[1]::INTEGER, parts[2]::INTEGER, parts[3]::INTEGER);
EXCEPTION
    WHEN OTHERS THEN
        RETURN NULL;
END;
$$;

COMMENT ON FUNCTION app.try_parse_date(TEXT)
    IS '安全解析 YYYY-MM-DD 或 YYYY/MM/DD，非法值返回 NULL';

