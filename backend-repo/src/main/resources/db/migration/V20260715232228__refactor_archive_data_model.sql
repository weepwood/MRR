CREATE OR REPLACE FUNCTION app.resolve_archive_id(
    p_bah TEXT,
    p_sjh TEXT,
    p_create_when_sjh_present BOOLEAN DEFAULT FALSE
)
RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE
    normalized_bah TEXT := app.normalize_medical_record_code(p_bah);
    normalized_sjh TEXT := app.normalize_medical_record_code(p_sjh);
    resolved_id BIGINT;
BEGIN
    IF normalized_sjh IS NOT NULL THEN
        SELECT id
        INTO resolved_id
        FROM app.mr_archive
        WHERE sjh = normalized_sjh;

        IF resolved_id IS NULL AND p_create_when_sjh_present THEN
            INSERT INTO app.mr_archive AS target (sjh, bah)
            VALUES (normalized_sjh, normalized_bah)
            ON CONFLICT (sjh) WHERE sjh IS NOT NULL DO UPDATE
            SET
                bah = COALESCE(target.bah, EXCLUDED.bah),
                updated_at = CURRENT_TIMESTAMP
            RETURNING id INTO resolved_id;
        END IF;

        RETURN resolved_id;
    END IF;

    IF normalized_bah IS NULL THEN
        RETURN NULL;
    END IF;

    -- 缺少上架号时，仅在病案号只对应一条主记录时自动关联，避免错误合并。
    SELECT MIN(id)
    INTO resolved_id
    FROM app.mr_archive
    WHERE bah = normalized_bah
    HAVING COUNT(*) = 1;

    RETURN resolved_id;
END;
$$;

COMMENT ON FUNCTION app.resolve_archive_id(TEXT, TEXT, BOOLEAN)
    IS '按上架号优先解析病案主键；缺少上架号时仅接受唯一病案号匹配';

CREATE OR REPLACE FUNCTION app.sync_archive_from_statistics()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    resolved_id BIGINT;
BEGIN
    NEW.bah := app.normalize_medical_record_code(NEW.bah);
    NEW.sjh := app.normalize_medical_record_code(NEW.sjh);

    IF NEW.archive_id IS NOT NULL THEN
        resolved_id := NEW.archive_id;
    ELSIF NEW.sjh IS NOT NULL THEN
        resolved_id := app.resolve_archive_id(NEW.bah, NEW.sjh, TRUE);
    ELSIF TG_OP = 'UPDATE' AND OLD.archive_id IS NOT NULL THEN
        resolved_id := OLD.archive_id;
    ELSE
        INSERT INTO app.mr_archive AS target (
            bah,
            patient_id,
            patient_name,
            inpatient_department,
            device_id,
            operator_no,
            archive_date,
            discharge_date,
            archive_type,
            page_count,
            source_statistics_id
        )
        VALUES (
            NEW.bah,
            NULLIF(BTRIM(NEW.patientid), ''),
            NULLIF(BTRIM(NEW.patientname), ''),
            NULLIF(BTRIM(NEW.inpatientdepartment), ''),
            NULLIF(BTRIM(NEW.cid), ''),
            NULLIF(BTRIM(NEW.openerno), ''),
            app.try_parse_date(NEW.date),
            app.try_parse_date(NEW.dischargedate),
            NULLIF(BTRIM(NEW.type), ''),
            NEW.pages,
            NEW.id
        )
        ON CONFLICT (source_statistics_id) DO UPDATE
        SET updated_at = CURRENT_TIMESTAMP
        RETURNING id INTO resolved_id;
    END IF;

    UPDATE app.mr_archive
    SET
        sjh = COALESCE(NEW.sjh, sjh),
        bah = COALESCE(NEW.bah, bah),
        patient_id = COALESCE(NULLIF(BTRIM(NEW.patientid), ''), patient_id),
        patient_name = COALESCE(NULLIF(BTRIM(NEW.patientname), ''), patient_name),
        inpatient_department = COALESCE(NULLIF(BTRIM(NEW.inpatientdepartment), ''), inpatient_department),
        device_id = COALESCE(NULLIF(BTRIM(NEW.cid), ''), device_id),
        operator_no = COALESCE(NULLIF(BTRIM(NEW.openerno), ''), operator_no),
        archive_date = COALESCE(app.try_parse_date(NEW.date), archive_date),
        discharge_date = COALESCE(app.try_parse_date(NEW.dischargedate), discharge_date),
        archive_type = COALESCE(NULLIF(BTRIM(NEW.type), ''), archive_type),
        page_count = COALESCE(NEW.pages, page_count),
        updated_at = CURRENT_TIMESTAMP
    WHERE id = resolved_id;

    NEW.archive_id := resolved_id;
    RETURN NEW;
END;
$$;

