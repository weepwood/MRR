          AND conrelid = 'app.mr_scan'::regclass
    ) THEN
        ALTER TABLE app.mr_scan
            ADD CONSTRAINT fk_mr_scan_archive
            FOREIGN KEY (archive_id) REFERENCES app.mr_archive(id)
            ON DELETE SET NULL NOT VALID;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_archive_box_record_archive'
          AND conrelid = 'app.mr_archive_box_record'::regclass
    ) THEN
        ALTER TABLE app.mr_archive_box_record
            ADD CONSTRAINT fk_archive_box_record_archive
            FOREIGN KEY (archive_id) REFERENCES app.mr_archive(id)
            ON DELETE SET NULL NOT VALID;
    END IF;
END;
$$;

CREATE OR REPLACE VIEW app.v_archive_summary AS
SELECT
    a.id,
    a.sjh,
    a.bah,
    a.patient_id,
    a.patient_name,
    a.inpatient_department,
    a.archive_date,
    a.discharge_date,
    a.archive_type,
    a.page_count,
    COUNT(s.id) AS scan_count,
    COALESCE(SUM(s.pages), 0) AS scan_page_count,
    a.created_at,
    a.updated_at
FROM app.mr_archive a
LEFT JOIN app.mr_scan s ON s.archive_id = a.id AND s.uploadflag <> 0
GROUP BY a.id;

COMMENT ON VIEW app.v_archive_summary IS '病案主数据与已关联影像数量汇总';
