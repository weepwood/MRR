-- Explicit single-scan link repair; no bulk or automatic medical-data mutation.
CREATE TABLE app.mrr_data_quality_repair_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id BIGINT NOT NULL,
    scan_id INTEGER NOT NULL,
    target_archive_id BIGINT NOT NULL,
    source_fingerprint TEXT NOT NULL,
    target_fingerprint TEXT NOT NULL,
    status VARCHAR(24) NOT NULL CHECK (status IN ('PROPOSED','APPROVED','APPLIED','VERIFIED','CANCELLED','COMPENSATED')),
    proposed_by BIGINT NOT NULL CHECK (proposed_by > 0),
    approved_by BIGINT CHECK (approved_by > 0 AND approved_by <> proposed_by),
    approved_at TIMESTAMPTZ,
    applied_revision TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CHECK ((approved_by IS NULL) = (approved_at IS NULL)),
    CHECK (status NOT IN ('APPROVED','APPLIED','VERIFIED','COMPENSATED') OR approved_by IS NOT NULL),
    CHECK (status NOT IN ('APPLIED','VERIFIED','COMPENSATED') OR applied_revision IS NOT NULL)
);

CREATE UNIQUE INDEX ux_quality_repair_active_scan
    ON app.mrr_data_quality_repair_order(scan_id)
    WHERE status IN ('PROPOSED','APPROVED','APPLIED','VERIFIED');

CREATE TABLE app.mrr_data_quality_repair_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES app.mrr_data_quality_repair_order(id),
    actor_id BIGINT NOT NULL CHECK (actor_id > 0),
    action VARCHAR(24) NOT NULL CHECK (action IN ('PROPOSED','APPROVED','APPLIED','VERIFIED','CANCELLED','COMPENSATED')),
    before_archive_id BIGINT,
    after_archive_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX idx_quality_repair_event_order ON app.mrr_data_quality_repair_event(order_id,id);
