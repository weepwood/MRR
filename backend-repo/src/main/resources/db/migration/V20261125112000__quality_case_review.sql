-- Human review decisions are independent from sampled findings and medical facts.
CREATE TABLE app.mrr_quality_case_review (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type VARCHAR(32) NOT NULL,
    entity_id BIGINT NOT NULL CHECK (entity_id > 0),
    check_code VARCHAR(80) NOT NULL,
    issue_id BIGINT NOT NULL CHECK (issue_id > 0),
    run_id BIGINT NOT NULL CHECK (run_id > 0),
    status VARCHAR(12) NOT NULL CHECK (status IN ('OPEN','CONFIRMED','IGNORED')),
    revision INTEGER NOT NULL CHECK (revision > 0),
    actor_id BIGINT NOT NULL CHECK (actor_id > 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    UNIQUE(entity_type,entity_id,check_code),
    CHECK ((entity_type='mr_scan' AND check_code='SCAN_ARCHIVE_LINK_MISSING_ESTIMATED' AND entity_id<=2147483647)
        OR (entity_type='mr_archive_box_record' AND check_code='BOX_ARCHIVE_LINK_MISSING'))
);
CREATE TABLE app.mrr_quality_case_review_event (
    case_id BIGINT NOT NULL REFERENCES app.mrr_quality_case_review(id),
    revision INTEGER NOT NULL CHECK (revision>0),
    issue_id BIGINT NOT NULL CHECK (issue_id>0),
    run_id BIGINT NOT NULL CHECK (run_id>0),
    status VARCHAR(12) NOT NULL CHECK (status IN ('OPEN','CONFIRMED','IGNORED')),
    reason VARCHAR(24) NOT NULL CHECK (reason IN ('CONFIRMED_EVIDENCE','DEFERRED_REVIEW','REOPEN_FOR_REVIEW')),
    actor_id BIGINT NOT NULL CHECK (actor_id>0),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY(case_id,revision)
);
