SET MODE PostgreSQL;
CREATE SCHEMA IF NOT EXISTS app;
SET SCHEMA app;

CREATE TABLE IF NOT EXISTS mr_archive (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sjh                    VARCHAR(64),
    bah                    VARCHAR(64),
    patient_id             VARCHAR(64),
    patient_name           VARCHAR(100),
    inpatient_department   VARCHAR(100),
    device_id              VARCHAR(64),
    operator_no            VARCHAR(64),
    archive_date           DATE,
    discharge_date         DATE,
    archive_type           VARCHAR(64),
    page_count             INTEGER,
    source_statistics_id   INTEGER,
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at             TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS mr_scan (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    archive_id  BIGINT REFERENCES mr_archive(id),
    brxh        VARCHAR(255),
    bah         VARCHAR(255),
    sjh         VARCHAR(255),
    filename    VARCHAR(255),
    btype       INTEGER,
    pages       INTEGER,
    openerno    VARCHAR(255),
    uploaddate  VARCHAR(255),
    uploadflag  INTEGER,
    folder      VARCHAR(255),
    oss_url     VARCHAR(512),
    file_size   BIGINT,
    checksum_md5 VARCHAR(64),
    migration_status VARCHAR(32),
    migrated_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS mr_record_type_dict (
    btype               SMALLINT PRIMARY KEY,
    type_code           VARCHAR(64) NOT NULL UNIQUE,
    type_name           VARCHAR(100) NOT NULL,
    keywords            TEXT NOT NULL DEFAULT '',
    negative_keywords   TEXT NOT NULL DEFAULT '',
    enabled             BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order          INTEGER NOT NULL DEFAULT 0,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS mr_classification_job (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    archive_id          BIGINT NOT NULL REFERENCES mr_archive(id),
    scope_type          VARCHAR(24) NOT NULL DEFAULT 'UNCLASSIFIED',
    status              VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    total_count         BIGINT NOT NULL DEFAULT 0,
    processed_count     BIGINT NOT NULL DEFAULT 0,
    suggested_count     BIGINT NOT NULL DEFAULT 0,
    no_match_count      BIGINT NOT NULL DEFAULT 0,
    failed_count        BIGINT NOT NULL DEFAULT 0,
    cursor_scan_id      INTEGER,
    model_version       VARCHAR(64),
    error_message       TEXT,
    created_by          VARCHAR(64),
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at          TIMESTAMP WITH TIME ZONE,
    completed_at        TIMESTAMP WITH TIME ZONE,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS mr_image_classification (
    scan_id              INTEGER PRIMARY KEY REFERENCES mr_scan(id),
    archive_id           BIGINT NOT NULL REFERENCES mr_archive(id),
    predicted_btype      SMALLINT REFERENCES mr_record_type_dict(btype),
    confidence           NUMERIC(6,5),
    classification_state VARCHAR(24) NOT NULL DEFAULT 'UNPROCESSED',
    effective_source     VARCHAR(32),
    model_version        VARCHAR(64),
    rule_version         VARCHAR(64),
    ocr_title            TEXT,
    evidence             JSON DEFAULT '{}',
    image_checksum       VARCHAR(32),
    reviewed_btype       SMALLINT REFERENCES mr_record_type_dict(btype),
    reviewed_by          VARCHAR(64),
    reviewed_at          TIMESTAMP WITH TIME ZONE,
    error_message        TEXT,
    classified_at        TIMESTAMP WITH TIME ZONE,
    updated_at           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS mr_image_type_audit (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_id             INTEGER NOT NULL REFERENCES mr_scan(id),
    archive_id          BIGINT REFERENCES mr_archive(id),
    previous_btype      SMALLINT,
    proposed_btype      SMALLINT,
    final_btype         SMALLINT,
    action              VARCHAR(32) NOT NULL,
    source              VARCHAR(32) NOT NULL,
    model_version       VARCHAR(64),
    confidence          NUMERIC(6,5),
    operated_by         VARCHAR(64),
    reason              TEXT,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

