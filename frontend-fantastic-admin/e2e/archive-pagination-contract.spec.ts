import { expect, test } from '@playwright/test'
import { isolateLocalVisualSettings } from './helpers/local-visual-settings'

test('扫描批次与病案档案袋使用公共分页和表格外观', async ({ page }) => {
  test.setTimeout(45_000)
  await isolateLocalVisualSettings(page)
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/records')
  const cursor = page.locator('.mrr-cursor-pagination')
  await expect(cursor).toBeVisible()
  await expect(cursor.getByRole('button', { name: '下一页', exact: true })).toBeEnabled()
  const next = cursor.getByRole('button', { name: '下一页', exact: true })
  await expect(next).toHaveCSS('height', '28px')
  await expect(next).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
  await expect(cursor.getByRole('button', { name: '上一页', exact: true })).toBeDisabled()
  const jump = cursor.locator('.el-pagination__jump input')
  await jump.fill('999999')
  await jump.press('Enter')
  await expect(cursor.getByRole('alert')).toBeVisible()
  await jump.fill('2')
  await jump.press('Enter')
  await expect(cursor.locator('.el-pager .is-active')).toHaveText('2')
  await expect(page.locator('.records-table td.mrr-table-sequence .cell').first()).toHaveText('21')
  await expect(jump).toBeEnabled()
  await jump.fill('1')
  await jump.press('Enter')
  await expect(cursor.locator('.el-pager .is-active')).toHaveText('1')
  await expect(jump).toBeEnabled()
  await expect(cursor.locator('.el-pagination__sizes [role=combobox]')).toBeEnabled()
  await cursor.locator('.el-pagination__sizes .el-select__wrapper').click()
  await page.getByRole('option', { name: '50 条/页', exact: true }).click()
  await expect(cursor.locator('.el-pagination__sizes .el-select__placeholder')).toHaveText('50 条/页')
  await expect(cursor.locator('.el-pager .is-active')).toHaveText('1')
  await page.goto('/statistics-detail')
  const panel = page.locator('.mrr-section-card').filter({ has: page.getByRole('heading', { name: '档案列表', exact: true }) })
  await expect(panel.locator('.archive-grid')).toBeVisible()
  await expect(panel.locator('.mrr-data-table-panel__pagination .el-pagination')).toBeVisible()
  await expect(panel.locator('.el-pagination__sizes')).toHaveCount(0)
  await panel.getByText('列表', { exact: true }).click()
  const table = panel.locator('.archive-list')
  await expect(table).toBeVisible()
  await expect(table).toHaveClass(/el-table--striped/)
  await expect(table.getByRole('columnheader', { name: '序号', exact: true })).toBeVisible()
  await expect(table.locator('td.mrr-table-sequence .cell').first()).toHaveText('1')
  await expect(panel.locator('.el-pagination__sizes')).toHaveCount(1)
  await panel.locator('.el-pagination__sizes .el-select__wrapper').click()
  await page.getByRole('option', { name: '10 条/页', exact: true }).click()
  await expect(panel.locator('.el-pagination__sizes .el-select__placeholder')).toHaveText('10 条/页')
  await expect(table).toBeVisible()
  await expect(table.locator('th.el-table__cell').first()).toHaveCSS('height', '42px')
  await expect(panel.locator('.el-pagination__total')).toHaveCount(1)
  for (const width of [1440, 375]) {
    await page.setViewportSize({ width, height: 900 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
    await expect.poll(() => panel.locator('.el-pagination').evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true)
  }
})
