import { expect, test } from '@playwright/test'

test('影像与OCR面板按实际空间调整，专注原图不重新加载且窄屏堆叠', async ({ page }) => {
  await page.setViewportSize({ width: 1920, height: 1000 })
  await page.goto('/archive-workbench')
  const search = page.getByRole('textbox', { name: '病案查询值' })
  await search.fill('26070000')
  await search.press('Enter')
  const list = page.getByRole('group', { name: '有效影像列表' })
  await list.getByRole('button').first().click()
  const image = page.getByAltText('待核对影像')
  await expect.poll(() => image.evaluate((el: HTMLImageElement) => el.complete && el.naturalWidth > 0)).toBe(true)
  const src = await image.getAttribute('src')
  const listHandle = page.getByRole('separator', { name: '调整影像列表宽度' })
  const ocrHandle = page.getByRole('separator', { name: '调整 OCR 检查器宽度' })
  const inspector = page.locator('.scan-inspector')
  const listPane = inspector.locator('.scan-list-pane')
  const ocrPane = inspector.locator('.scan-ocr-pane')
  const width = (el: typeof inspector) => el.evaluate(node => node.getBoundingClientRect().width)
  await expect(listHandle).toBeVisible()
  await expect(ocrHandle).toHaveCount(0)
  const viewWidth = await width(inspector.locator('.scan-main .scan-viewport'))
  await page.getByRole('button', { name: '识别文字', exact: true }).click()
  await expect(page.getByRole('region', { name: '影像文字识别' })).toBeVisible()
  await expect(ocrHandle).toBeVisible()
  await expect.poll(() => width(inspector.locator('.scan-main .scan-viewport'))).toBeLessThan(viewWidth)
  await expect.poll(() => width(listPane)).toBeCloseTo(168, 0)
  await listHandle.focus()
  await listHandle.press('ArrowRight')
  await expect.poll(() => width(listPane)).toBeCloseTo(178, 0)
  const ocrBefore = await width(ocrPane)
  const bounds = (await ocrHandle.boundingBox())!
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + 15)
  await page.mouse.down()
  try {
    await page.mouse.move(bounds.x + bounds.width / 2 - 30, bounds.y + 15, { steps: 5 })
    await expect.poll(() => width(ocrPane)).toBeCloseTo(ocrBefore + 30, 0)
  }
  finally { await page.mouse.up() }
  await ocrHandle.focus()
  await ocrHandle.press('ArrowRight')
  await expect.poll(() => width(ocrPane)).toBeCloseTo(ocrBefore + 20, 0)
  await ocrHandle.press('Enter')
  await expect.poll(() => width(ocrPane)).toBeCloseTo(320, 0)
  const viewport = page.getByRole('region', { name: '原图滚动查看区' })
  const height = await viewport.evaluate(el => el.clientHeight)
  await page.getByRole('button', { name: '专注原图' }).click()
  await expect(ocrHandle).toHaveCount(0)
  await expect(page.getByRole('region', { name: '影像文字识别' })).toHaveCount(0)
  await expect.poll(() => viewport.evaluate(el => el.clientHeight)).toBeGreaterThan(height)
  await expect(image).toHaveAttribute('src', src!)
  await expect(list).toBeVisible()
  await page.getByRole('button', { name: '恢复布局' }).click()
  await expect(ocrHandle).toHaveCount(0)
  await expect(page.getByRole('button', { name: '识别文字', exact: true })).toBeVisible()
  await expect(image).toHaveAttribute('src', src!)
  await page.getByRole('button', { name: '识别文字', exact: true }).click()
  await expect(ocrHandle).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('v12-panels-desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 1100, height: 900 })
  await expect(ocrHandle).toHaveCount(0)
  await expect(page.getByRole('region', { name: '影像文字识别' })).toBeVisible()
  await page.getByRole('button', { name: '收起 OCR', exact: true }).click()
  await expect(page.getByRole('region', { name: '影像文字识别' })).toHaveCount(0)
  for (const width of [1100, 760, 390]) {
    await page.setViewportSize({ width, height: 900 })
    await expect(ocrHandle).toHaveCount(0)
    await expect.poll(() => inspector.evaluate((el) => {
      const box = el.getBoundingClientRect()
      if (el.scrollWidth <= el.clientWidth + 2) { return [] }
      return [{ viewport: innerWidth, panel: el.clientWidth, scroll: el.scrollWidth, overflowing: [...el.querySelectorAll('*')]
        .filter(node => !node.closest('.scan-viewport, .scan-list'))
        .filter(node => node.getBoundingClientRect().width > 0 && node.getBoundingClientRect().right > box.right + 2)
        .slice(0, 12)
        .map(node => ({ element: node.tagName, class: String(node.className), width: node.getBoundingClientRect().width })) }]
    }), { message: `影像核对在 ${width}px 视口不允许横向溢出` }).toEqual([])
    await expect(image).toHaveAttribute('src', src!)
  }
  await page.addStyleTag({ content: '.scan-inspector button { letter-spacing: 1px; }' })
  await expect.poll(() => inspector.evaluate(el => el.scrollWidth <= el.clientWidth + 2)).toBe(true)
  await expect(listHandle).toHaveCount(0)
  await page.screenshot({ path: test.info().outputPath('v12-panels-mobile.png'), fullPage: true })
})
