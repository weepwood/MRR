import { expect, test } from '@playwright/test'
import { isolateLocalVisualSettings } from './helpers/local-visual-settings'

test('普通模式鼠标长按排序、取消及输入框保护', async ({ page }) => {
  await isolateLocalVisualSettings(page)
  await page.goto('/')
  const records = page.locator('[data-widget-id="records"]')
  const stats = page.locator('[data-widget-id="statistics"]')
  const order = () => page.locator('.dashboard-grid > article').evaluateAll(els => els.map(el => (el as HTMLElement).dataset.widgetId))
  const before = await order()
  const source = (await records.locator('.dashboard-widget__icon').boundingBox())!
  const target = (await stats.locator('.dashboard-widget__icon').boundingBox())!
  await page.mouse.move(source.x + 15, source.y + 15)
  await page.mouse.down()
  await expect(records).toHaveClass(/is-dragging/)
  await page.mouse.move(target.x + 15, target.y + 15, { steps: 5 })
  await expect(stats).toHaveClass(/is-drag-over/)
  await expect.poll(async () => (await order()).indexOf('records')).toBeGreaterThan((await order()).indexOf('statistics'))
  await page.mouse.up()
  await expect(records).not.toHaveClass(/is-dragging/)
  expect((await order()).indexOf('records')).toBeGreaterThan((await order()).indexOf('statistics'))
  await expect(page).toHaveURL(/\/$/)
  const changed = await order()
  expect(changed).not.toEqual(before)
  await page.reload()
  await expect.poll(order).toEqual(changed)
  const field = page.getByRole('textbox', { name: '病案号', exact: true })
  const input = (await field.boundingBox())!
  await page.mouse.move(input.x + 10, input.y + 10)
  await page.mouse.down()
  await page.waitForTimeout(450)
  await expect(page.locator('.dashboard-widget.is-dragging')).toHaveCount(0)
  await page.mouse.up()
  await field.fill('123456')
  await expect(field).toHaveValue('123456')
  const r = (await records.locator('.dashboard-widget__icon').boundingBox())!
  await page.mouse.move(r.x + 15, r.y + 15)
  await page.mouse.down()
  await expect(records).toHaveClass(/is-dragging/)
  await page.keyboard.press('Escape')
  await page.mouse.up()
  await expect(records).not.toHaveClass(/is-dragging/)
  expect(await order()).toEqual(changed)
  await expect(page).toHaveURL(/\/$/)
})

for (const [palette, theme] of [['mrr', 'light'], ['mrr', 'dark'], ['gr8r', 'light'], ['gr8r', 'dark']] as const) {
  test(`${palette}/${theme} 独立图标底色与持久化`, async ({ page }, info) => {
    await isolateLocalVisualSettings(page)
    await page.addInitScript(({ palette, theme }) => localStorage.setItem('MRR-ADMIN:app-settings', JSON.stringify({
      app: { themePalette: palette, colorScheme: theme, enableMotion: false },
      layout: { enableMobileAdaptation: true },
    })), { palette, theme })
    await page.goto('/')
    const card = page.locator('[data-widget-id="archive"]')
    const icon = card.locator('.dashboard-widget__icon')
    const original = await card.evaluate(el => getComputedStyle(el).backgroundColor)
    await page.locator('.dashboard-header').hover()
    await page.getByRole('button', { name: '管理模块' }).click()
    const manager = page.getByRole('dialog', { name: '管理小组件' })
    await manager.locator('.widget-manager-item').filter({ hasText: '影像档案袋' }).getByRole('button', { name: '编辑' }).click()
    const editor = page.getByRole('dialog', { name: '编辑小组件' })
    const icons = editor.getByRole('group', { name: '图标颜色' })
    const surfaces = editor.getByRole('group', { name: '卡片底色' })
    await expect(icons.getByRole('button')).toHaveCount(12)
    await expect(surfaces.getByRole('button')).toHaveCount(12)
    await icons.getByRole('button', { name: '玫粉', exact: true }).click()
    await surfaces.getByRole('button', { name: '湖蓝', exact: true }).click()
    await expect(icons.getByRole('button', { name: '玫粉' })).toHaveAttribute('aria-pressed', 'true')
    await expect(surfaces.getByRole('button', { name: '湖蓝' })).toHaveAttribute('aria-pressed', 'true')
    await page.screenshot({ path: info.outputPath('editor.png') })
    await editor.getByRole('button', { name: '保存', exact: true }).click()
    await manager.getByRole('button', { name: '完成', exact: true }).click()
    await expect(card).toHaveClass(/dashboard-widget--color-cyan/)
    await expect.poll(() => card.evaluate(el => getComputedStyle(el).backgroundColor)).not.toBe(original)
    await expect(icon).toHaveCSS('color', theme === 'dark' ? 'rgb(240, 147, 189)' : 'rgb(181, 45, 112)')
    const current = await card.evaluate(el => getComputedStyle(el).backgroundColor)
    await page.screenshot({ path: info.outputPath('home.png'), fullPage: true })
    await page.reload()
    await expect(card).toHaveCSS('background-color', current)
    await expect(icon).toHaveCSS('color', theme === 'dark' ? 'rgb(240, 147, 189)' : 'rgb(181, 45, 112)')
  })
}

test.describe('触控长按', () => {
  test.use({ hasTouch: true, viewport: { width: 390, height: 900 } })
  test('真实触控事件长按换位，普通滑动不启动拖拽', async ({ page, context }) => {
    await isolateLocalVisualSettings(page)
    await page.goto('/')
    const records = page.locator('[data-widget-id="records"]')
    const stats = page.locator('[data-widget-id="statistics"]')
    await records.scrollIntoViewIfNeeded()
    const client = await context.newCDPSession(page)
    const point = async (id: typeof records) => {
      const rect = (await id.locator('.dashboard-widget__icon').boundingBox())!
      return { x: Math.round(rect.x + 15), y: Math.round(rect.y + 15) }
    }
    const start = await point(records)
    const end = await point(stats)
    await client.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [start] })
    await expect(records).toHaveClass(/is-dragging/)
    await client.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [end] })
    await expect(stats).toHaveClass(/is-drag-over/)
    const draft = await page.locator('.dashboard-grid > article').evaluateAll(els => els.map(el => (el as HTMLElement).dataset.widgetId))
    expect(draft.indexOf('records')).toBeGreaterThan(draft.indexOf('statistics'))
    await client.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await expect(records).not.toHaveClass(/is-dragging/)
    const order = await page.locator('.dashboard-grid > article').evaluateAll(els => els.map(el => (el as HTMLElement).dataset.widgetId))
    expect(order.indexOf('records')).toBeGreaterThan(order.indexOf('statistics'))
    await expect(page).toHaveURL(/\/$/)
    const next = await point(records)
    await client.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [next] })
    await client.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: next.x, y: next.y - 80 }] })
    await page.waitForTimeout(420)
    await expect(page.locator('.dashboard-widget.is-dragging')).toHaveCount(0)
    await client.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await client.detach()
  })
})
