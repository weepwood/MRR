import { expect, test } from '@playwright/test'

test('外观设置与展厅开关使用唯一实现，键盘及禁用状态保持正常', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/settings?section=appearance')
  const motion = page.getByRole('switch', { name: '动态效果', exact: true })
  await expect(motion).toHaveCount(1)
  await expect(page.locator('.app-config-panel .el-switch').first()).toBeVisible()
  await expect(page.locator('.app-config-panel .fa-switch')).toHaveCount(0)
  await expect(page.locator('.app-config-panel .el-switch')).not.toHaveCount(0)
  const initial = await motion.getAttribute('aria-checked')
  await motion.focus()
  await motion.press('Space')
  await expect(motion).toHaveAttribute('aria-checked', initial === 'true' ? 'false' : 'true')
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('MRR-ADMIN:app-settings') || '{}').app?.enableMotion ?? true)).toBe(initial !== 'true')
  await page.reload()
  await expect(motion).toHaveAttribute('aria-checked', initial === 'true' ? 'false' : 'true')
  await motion.focus()
  await motion.press('Space')
  await expect(motion).toHaveAttribute('aria-checked', initial!)
  await page.goto('/ui-components')
  const input = page.getByLabel('查找组件', { exact: true })
  await input.fill('ElSwitch')
  await expect(page.getByRole('heading', { name: '选择与开关', exact: true })).toBeVisible()
  const demo = page.getByRole('switch', { name: '启用示例', exact: true })
  const before = await demo.getAttribute('aria-checked')
  await page.locator('.example-row').filter({ has: demo }).locator('.el-switch__core').first().click()
  await expect(demo).toHaveAttribute('aria-checked', before === 'true' ? 'false' : 'true')
  await expect(page.getByRole('switch', { name: '禁用开关', exact: true })).toBeDisabled()
  await expect(page.locator('.fa-switch')).toHaveCount(0)
})
