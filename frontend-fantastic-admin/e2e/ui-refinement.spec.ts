import { expect, test } from '@playwright/test'
import { isolateLocalVisualSettings } from './helpers/local-visual-settings'

for (const palette of ['mrr', 'gr8r']) {
  for (const theme of ['light', 'dark']) {
    test(`展厅卡片和局部预览隔离 ${palette}/${theme}`, async ({ page }, testInfo) => {
      await isolateLocalVisualSettings(page)
      await page.addInitScript(({ palette, theme }) => localStorage.setItem('MRR-ADMIN:app-settings', JSON.stringify({
        app: { themePalette: palette, colorScheme: theme, enableMotion: true },
        menu: { mode: 'single' },
        layout: { enableMobileAdaptation: true },
      })), { palette, theme })
      await page.setViewportSize({ width: 1440, height: 900 })
      await page.goto('/ui-components')
      const search = page.getByLabel('查找组件', { exact: true })
      await search.fill('ElInput')
      const article = page.locator('.gallery-example').first()
      await expect(article.locator('.mrr-section-card > .el-card__header')).toBeVisible()
      const title = article.getByRole('heading', { name: '输入与筛选', exact: true })
      await expect(title).toBeVisible()
      const input = article.getByLabel('示例名称', { exact: true })
      await input.fill('局部预览保留值')
      const settings = await page.evaluate(() => localStorage.getItem('MRR-ADMIN:app-settings'))
      await article.getByRole('button', { name: '窄宽预览：输入与筛选' }).click()
      await expect(article.locator('.gallery-preview')).toHaveClass(/gallery-preview--compact/)
      await expect.poll(() => article.locator('.gallery-preview').evaluate(el => el.getBoundingClientRect().width <= 420 && el.scrollWidth <= el.clientWidth + 1)).toBe(true)
      await expect(input).toHaveValue('局部预览保留值')
      const number = article.getByRole('spinbutton')
      await number.focus()
      await expect(article.locator('.el-input-number')).toHaveCSS('outline-style', 'solid')
      await number.press('ArrowUp')
      await expect(number).toHaveValue('4')
      const select = article.getByLabel('示例来源', { exact: true })
      await article.locator('.example-field').filter({ has: page.getByText('示例来源', { exact: true }) }).locator('.el-select__wrapper').click({ timeout: 5000 })
      const selectedOption = page.locator('.el-select__popper:visible .el-select-dropdown__item.is-selected')
      await expect(selectedOption).toHaveText('本地示例')
      const selectedColor = await selectedOption.evaluate(el => getComputedStyle(el).backgroundColor)
      const otherOption = page.getByRole('option', { name: '归档示例', exact: true })
      expect(await otherOption.evaluate(el => getComputedStyle(el).backgroundColor)).not.toBe(selectedColor)
      await otherOption.click()
      await expect(select).toHaveAttribute('aria-expanded', 'false')
      const date = article.getByLabel('示例日期', { exact: true })
      await date.click()
      const currentDate = page.locator('.el-picker__popper:visible .el-date-table td.current .el-date-table-cell__text')
      await expect(currentDate).toBeVisible()
      const dateColor = await currentDate.evaluate((el) => {
        const s = getComputedStyle(el)
        return { foreground: s.color, background: s.backgroundColor }
      })
      expect(dateColor.foreground).not.toBe(dateColor.background)
      await date.press('Escape')
      await expect(currentDate).not.toBeVisible()
      await article.getByRole('button', { name: '重置示例：输入与筛选' }).click()
      await expect(input).toHaveValue('组件演示')
      await expect(number).toHaveValue('3')
      expect(await page.evaluate(() => localStorage.getItem('MRR-ADMIN:app-settings'))).toBe(settings)
      await article.screenshot({ path: testInfo.outputPath('compact.png'), animations: 'disabled' })
      await search.fill('ElSwitch')
      const matrix = page.locator('.selection-matrix')
      await expect(matrix).toBeVisible()
      await expect(matrix.getByRole('switch', { name: '矩阵禁用开关' })).toBeDisabled()
      const toggle = matrix.getByRole('switch', { name: '矩阵开关' })
      await toggle.focus()
      await toggle.press('Space')
      await expect(toggle).toHaveAttribute('aria-checked', 'true')
      const mixed = matrix.getByRole('checkbox', { name: '矩阵半选复选框' })
      await expect(mixed).toHaveJSProperty('indeterminate', true)
      await mixed.focus()
      await mixed.press('Space')
      await expect(mixed).toHaveJSProperty('indeterminate', false)
      await expect(mixed).toBeChecked()
      await page.emulateMedia({ reducedMotion: 'reduce' })
      await expect.poll(() => matrix.locator('.el-switch__action').first().evaluate(el => Number.parseFloat(getComputedStyle(el).transitionDuration))).toBe(0)
      await page.setViewportSize({ width: 375, height: 900 })
      await expect.poll(() => matrix.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true)
      await matrix.screenshot({ path: testInfo.outputPath('matrix.png'), animations: 'disabled' })
    })
  }
}
