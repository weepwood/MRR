import { expect, test } from '@playwright/test'

for (const theme of ['light', 'dark']) {
  test(`${theme} 病案检索前后状态与授权表快捷入口在桌面及窄屏可操作`, async ({ page }) => {
    await page.addInitScript(theme => localStorage.setItem('MRR-ADMIN:app-settings', JSON.stringify({
      app: { colorScheme: theme, enableMotion: false },
      menu: { mode: 'single' },
      layout: { enableMobileAdaptation: true },
    })), theme)
    await page.setViewportSize({ width: 1440, height: 900 })
    await page.goto('/archive-workbench')
    const guide = page.locator('.archive-start-card')
    await expect(guide.getByRole('heading', { name: '开始病案核对' })).toBeVisible()
    await expect(page.getByRole('heading', { name: '病案主档候选' })).toHaveCount(0)
    await expect.poll(() => page.locator('html').evaluate(el => el.classList.contains('dark'))).toBe(theme === 'dark')
    const search = page.getByRole('textbox', { name: '病案查询值', exact: true })
    await expect(search).toHaveAttribute('placeholder', '输入病案号')
    await guide.getByRole('button', { name: '返回检索' }).click()
    await expect(search).toBeFocused()
    await page.locator('.search-type').click({ timeout: 5000 })
    await page.getByRole('option', { name: '上架号 SJH', exact: true }).click()
    await expect(search).toHaveAttribute('placeholder', '输入上架号')
    await page.locator('.search-type').click({ timeout: 5000 })
    await page.getByRole('option', { name: '病案号 BAH', exact: true }).click()
    await page.screenshot({ path: test.info().outputPath(`${theme}-archive-start.png`) })
    await page.setViewportSize({ width: 390, height: 844 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: test.info().outputPath(`${theme}-archive-start-mobile.png`) })
    await search.fill('999999999')
    await search.press('Enter')
    await expect(guide.getByRole('heading', { name: '未找到匹配病案' })).toBeVisible()
    await search.fill('26070000')
    await search.press('Enter')
    await expect(page.getByText('病案主档 #1', { exact: true })).toBeVisible()
    await expect(guide).toHaveCount(0)
    await expect(page.getByRole('button', { name: '查看病案主档 1 的关系' })).toBeVisible()
    await page.setViewportSize({ width: 1440, height: 900 })
    await page.goto('/database-browse')
    const directory = page.getByRole('region', { name: '已授权数据表' })
    await expect(directory.getByRole('button')).toHaveCount(2)
    await expect(directory.getByText('scan · 64 行')).toBeVisible()
    await expect(page.getByRole('combobox', { name: '数据表' })).toBeVisible()
    await page.screenshot({ path: test.info().outputPath(`${theme}-database-directory.png`) })
    await page.setViewportSize({ width: 390, height: 844 })
    await expect.poll(() => directory.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true)
    await page.screenshot({ path: test.info().outputPath(`${theme}-database-directory-mobile.png`) })
    const card = directory.getByRole('button', { name: '浏览影像记录（合成）' })
    await card.focus()
    await expect(card).toBeFocused()
    await card.press('Enter')
    await expect(page.getByText('第 1 页 · 本页 50 行', { exact: false })).toBeVisible()
    await expect(directory).toHaveCount(0)
    await expect(page.getByRole('combobox', { name: '数据表' })).toBeVisible()
  })
}
