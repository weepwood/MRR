"""Rebuild local UI subsets; ordinary frontend builds use committed assets."""

import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / "public" / "fonts"
CSS = ROOT / "src" / "assets" / "styles" / "fonts.css"
MANIFEST = FONTS / "ui-fonts.json"
WEIGHTS = [(400, "regular"), (500, "medium"), (700, "bold")]


def digest(data):
    return hashlib.sha256(data).hexdigest()


def ranges(points):
    result = []
    for point in sorted(points):
        if result and point == result[-1][1] + 1:
            result[-1][1] = point
        else:
            result.append([point, point])
    return result


def unicode_css(intervals):
    return ", ".join(f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}" for start, end in intervals)


def parse_unicode_css(text):
    return [[int(bounds[0], 16), int(bounds[-1], 16)]
            for value in text.split(",") if (bounds := value.strip().removeprefix("U+").split("-"))]


def complement(intervals):
    result = []
    previous = 0
    for start, end in intervals:
        if previous < start:
            result.append([previous, start - 1])
        previous = end + 1
    if previous <= 0x10FFFF:
        result.append([previous, 0x10FFFF])
    return result


def source_characters():
    # The census includes synthetic mock labels; excludes tests, declarations and icon data.
    points = set(range(0x20, 0x7F)) | set(range(0x2000, 0x2070)) | set(range(0x3000, 0x3040))
    for path in sorted((ROOT / "src").rglob("*")):
        if path.suffix not in {".vue", ".ts", ".json"}:
            continue
        if any(part in {"__tests__", "iconify"} for part in path.parts):
            continue
        if path.name.endswith((".test.ts", ".spec.ts", ".d.ts")):
            continue
        points.update(ord(character) for character in path.read_text(encoding="utf-8-sig"))
    return points


def stylesheet(entries, common):
    header = (
        "/* Generated by scripts/build-ui-fonts.py; self-hosted HarmonyOS Sans SC.\n"
        " * Original source: https://github.com/IKKI2000/harmonyos-fonts\n"
        " * Original fonts and embedded licensing metadata are retained.\n"
        " * UI characters use subsets; other characters use the original full fonts. */\n"
    )
    faces = []
    for entry in entries:
        for filename, intervals in [(entry["source"], complement(common)), (entry["subset"], common)]:
            faces.append(
                '@font-face {\n  font-family: "HarmonyOS Sans SC";\n'
                f'  font-style: normal;\n  font-weight: {entry["weight"]};\n'
                f'  src: url("/fonts/{filename}") format("woff2");\n'
                f'  font-display: swap;\n  unicode-range: {unicode_css(intervals)};\n}}\n'
            )
    return header + "\n".join(faces)


def build():
    from fontTools import subset
    from fontTools.ttLib import TTFont

    inputs = [(weight, name, FONTS / f"harmonyos-sans-sc-{name}.woff2") for weight, name in WEIGHTS]
    maps = [set(TTFont(path).getBestCmap()) for _, _, path in inputs]
    points = source_characters() & set.intersection(*maps)
    common = ranges(points)
    entries = []
    for weight, name, path in inputs:
        font = TTFont(path, recalcTimestamp=False)
        options = subset.Options()
        options.name_IDs = ["*"]
        options.name_languages = ["*"]
        options.name_legacy = True
        options.layout_features = ["*"]
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=points)
        subsetter.subset(font)
        temporary = FONTS / f"harmonyos-sans-sc-ui-{name}.tmp.woff2"
        try:
            font.save(temporary)
            data = temporary.read_bytes()
        finally:
            temporary.unlink(missing_ok=True)
        sha = digest(data)
        filename = f"harmonyos-sans-sc-ui-{name}-{sha[:12]}.woff2"
        (FONTS / filename).write_bytes(data)
        entries.append({"weight": weight, "source": path.name, "sourceSha256": digest(path.read_bytes()),
                        "subset": filename, "subsetSha256": sha, "bytes": len(data)})
    CSS.write_text(stylesheet(entries, common), encoding="utf-8", newline="\n")
    manifest = {"schemaVersion": 1, "commonUnicodeRange": unicode_css(common), "fonts": entries}
    MANIFEST.write_text(json.dumps(manifest, ensure_ascii=True, indent=2) + "\n", encoding="utf-8", newline="\n")
    # Remove only obsolete generated subsets inside this fixed asset directory.
    keep = {entry["subset"] for entry in entries}
    for path in FONTS.glob("harmonyos-sans-sc-ui-*.woff2"):
        if path.name not in keep:
            path.unlink()
    print(f"UI font subsets: {len(points)} codepoints, {sum(entry['bytes'] for entry in entries)} bytes")


def check():
    from fontTools.pens.recordingPen import DecomposingRecordingPen
    from fontTools.ttLib import TTFont

    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    common = parse_unicode_css(manifest["commonUnicodeRange"])
    common_points = {point for start, end in common for point in range(start, end + 1)}
    entries = manifest["fonts"]
    assert CSS.read_text(encoding="utf-8") == stylesheet(entries, common), "CSS ranges do not match manifest"
    # Parse the shipped CSS, then verify every original encoding against both actual cmaps.
    css_ranges = [parse_unicode_css(text) for text in re.findall(r"unicode-range: ([^;]+);", CSS.read_text(encoding="utf-8"))]
    def contains(intervals, point):
        return any(start <= point <= end for start, end in intervals)
    for index, entry in enumerate(entries):
        original = FONTS / entry["source"]
        generated = FONTS / entry["subset"]
        assert digest(original.read_bytes()) == entry["sourceSha256"], "Original font changed"
        assert digest(generated.read_bytes()) == entry["subsetSha256"], "Subset bytes changed"
        assert generated.stat().st_size == entry["bytes"]
        original_font = TTFont(original)
        subset_font = TTFont(generated)
        original_map = original_font.getBestCmap()
        subset_map = subset_font.getBestCmap()
        assert set(subset_map) == common_points, "Unexpected subset encoding"
        for table, fields in [("hhea", ["ascent", "descent", "lineGap"]), ("OS/2", ["sTypoAscender", "sTypoDescender", "sTypoLineGap", "usWinAscent", "usWinDescent", "fsType"])]:
            assert all(getattr(original_font[table], field) == getattr(subset_font[table], field) for field in fields), "Font metrics changed"
        for name_id in [0, 13, 14]:
            names = lambda font: {record.toUnicode() for record in font["name"].names if record.nameID == name_id}
            assert names(original_font) == names(subset_font), "Copyright/license metadata changed"
        original_glyphs, subset_glyphs = original_font.getGlyphSet(), subset_font.getGlyphSet()
        for point, glyph in original_map.items():
            in_full = contains(css_ranges[index * 2], point)
            in_subset = contains(css_ranges[index * 2 + 1], point)
            assert in_full != in_subset, f"Missing/overlapping U+{point:X}"
            assert glyph != ".notdef"
            if in_subset:
                assert subset_map[point] != ".notdef"
                expected = DecomposingRecordingPen(original_glyphs)
                actual = DecomposingRecordingPen(subset_glyphs)
                original_glyphs[glyph].draw(expected)
                subset_glyphs[subset_map[point]].draw(actual)
                assert expected.value == actual.value, f"Glyph outline changed: U+{point:X}"
                assert original_font["hmtx"].metrics[glyph] == subset_font["hmtx"].metrics[subset_map[point]], "Glyph metrics changed"
    assert set.intersection(*(set(TTFont(FONTS / entry["source"]).getBestCmap()) for entry in entries)) & source_characters() <= common_points, "UI census changed; rebuild subsets"
    print(f"Verified {len(entries)} weights, hashes, glyph outlines/metrics, licensing metadata, UI census and full original coverage")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    check() if args.check else build()
